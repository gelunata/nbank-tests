#!/bin/bash

# Название локального образа с тестами
IMAGE_NAME="nbank-tests:latest"

# Функция гарантированной очистки окружения
cleanup() {
    echo ""
    echo "🧹 [ОЧИСТКА] Автоматически останавливаем тестовое окружение..."
    docker compose down
    echo "✅ [ЗАВЕРШЕНО] Окружение успешно остановлено и очищено."
}

# Регистрируем trap: функция cleanup сработает ВСЕГДА (при успехе, ошибке тестов или Ctrl+C)
trap cleanup EXIT INT TERM

echo "🚀 [СТАРТ] Начало процесса автоматического тестирования..."

# 1. Собираем образ тестов из Dockerfile
echo "🔨 [1/4] Сборка Docker-образа с тестами..."
if docker build -t "$IMAGE_NAME" .; then
    echo "✅ Образ тестов успешно собран."
else
    echo "❌ Ошибка при сборке образа с тестами! Процесс остановлен."
    exit 1
fi

# 2. Поднимаем тестовое окружение строго по ТЗ
echo "🐳 [2/4] Поднимаем тестовое окружение (docker compose up -d)..."
docker compose -f ./infa/docker_compose/docker-compose.yml up -d

# Даем бэкенду и селеноиду 15 секунд, чтобы успели запуститься и открыть порты на localhost
echo "⏳ Ожидание готовности сервисов..."
sleep 15

# 3. Запускаем контейнер с тестами строго по ТЗ
echo "🧪 [3/4] Запуск контейнера с тестами через docker run..."
echo "----------------------------------------------------------------------"

# Все переменные окружения и флаг --rm переданы в точности по тексту задания.
# network="host" склеивает localhost контейнера с портами твоей машины.
docker run --rm \
  --name "nbank-autotests" \
  --network="host" \
  -e APIBASEURL="http://localhost:4111" \
  -e UIBASEURL="http://localhost:3000" \
  -e SELENOID_URL="http://localhost:4444" \
  -e SELENOID_UI_URL="http://localhost:8080" \
  "$IMAGE_NAME"

# Запоминаем код завершения тестов (0 - успех, не 0 - ошибка)
TEST_EXIT_CODE=$?
echo "----------------------------------------------------------------------"

# 4. Выводим понятный статус для разработчика
echo "📝 [4/4] Анализ результатов..."
if [ $TEST_EXIT_CODE -eq 0 ]; then
    echo "🎉 [РЕЗУЛЬТАТ] Все тесты успешно пройдены!"
else
    echo "❌ [РЕЗУЛЬТАТ] Тесты завершились с ошибкой (Exit code: $TEST_EXIT_CODE)."
fi

# Скрипт завершает работу, после чего автоматически срабатывает trap cleanup
exit $TEST_EXIT_CODE
